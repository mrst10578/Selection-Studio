export function taxonomySummary(record){
  const cfg=TAXONOMY.subjects?.[record?.subject];
  if(!cfg)return "";
  if(record?.subject==="MATH"){
    const topic=cfg.topics?.[String(record?.chapter||"")];
    const unit=topic?.units?.[String(record?.unit||"")];
    const a=topic?.name_fa||"مبحث اصلی ثبت نشده";
    const b=unit?.label_fa||unit?.name_fa||"زیرعنوان ثبت نشده";
    return a+" · "+b;
  }
  const grade=cfg.grades?.[String(record?.grade||"")];
  const chapter=grade?.chapters?.[String(record?.chapter||"")];
  const unit=chapter?.units?.[String(record?.unit||"")];
  const g=grade?.name_fa||String(record?.grade||"");
  const c=chapter?.name_fa?cfg.chapter_name_fa+" "+Number(record.chapter)+" ("+chapter.name_fa+")":cfg.chapter_name_fa+" "+(Number(record?.chapter)||"-");
  const u=unit?.name_fa?cfg.unit_name_fa+" "+Number(record.unit)+" ("+unit.name_fa+")":cfg.unit_name_fa+" "+(Number(record?.unit)||"-");
  return g+" · "+c+" · "+u;
}
